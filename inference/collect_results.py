"""Collect the results of the video inference and of the CholecSeg8k evaluation for
the three backbones into one plain-text recap (results_ex_2.txt).

Usage (from /homes/eprato01/ATLAS-model):
    .venv/bin/python inference/collect_results.py            # writes ./results_ex_2.txt

Runs that are not finished yet are shown as "pending"; just re-run the script
when the SLURM jobs are done.
"""

import argparse
import csv
import json
from datetime import date
from pathlib import Path

from eval_cholecseg8k import CLASS_NAMES, EVAL_CLASSES, IGNORED_GT, REPO_ROOT

MODELS = ["vits", "vitb", "vitl"]
MODEL_LABEL = {"vits": "ViT-S", "vitb": "ViT-B", "vitl": "ViT-L"}
CHOLEC_NAMES = {  # CholecSeg8k watershed-mask value -> class name (Hong et al., 2020)
    50: "Black background", 11: "Abdominal wall", 21: "Liver", 13: "Gastrointestinal tract",
    12: "Fat", 31: "Grasper", 23: "Connective tissue", 24: "Blood", 25: "Cystic duct",
    32: "L-hook electrocautery", 22: "Gallbladder", 33: "Hepatic vein", 5: "Liver ligament",
}


def load_json(path):
    return json.loads(path.read_text()) if path.exists() else None


def fmt(v, spec):
    if v is None:
        return "pending"
    if isinstance(v, str):
        return v
    return format(v, spec)


def table(header, rows, first_w=34, col_w=14):
    lines = [f"{header[0]:<{first_w}}" + "".join(f"{h:>{col_w}}" for h in header[1:])]
    lines.append("-" * len(lines[0]))
    for r in rows:
        lines.append(f"{r[0]:<{first_w}}" + "".join(f"{c:>{col_w}}" for c in r[1:]))
    return "\n".join(lines)


EFFICIENCY_ROWS = [
    # (label, key in profiling dict, format)
    ("GPU", "device", ""),
    ("Parameters (M)", "num_params_M", ".1f"),
    ("Input resolution (WxH)", "input_resolution", ""),
    ("Resized for the model (WxH)", "model_resized_resolution", ""),
    ("Windows per frame (256x256)", "windows_per_frame", "d"),
    ("Batch size (frames)", "batch_size", "d"),
    ("Peak GPU memory, PyTorch alloc (GB)", "peak_gpu_mem_allocated_gb", ".2f"),
    ("Peak GPU memory, PyTorch reserved (GB)", "peak_gpu_mem_reserved_gb", ".2f"),
    ("Peak GPU memory, nvidia-smi (GB)", "peak_gpu_mem_nvml_gb", ".2f"),
    ("Peak RAM, main + workers PSS (GB)", "peak_ram_total_pss_gb", ".2f"),
    ("Peak RAM, main process incl. load (GB)", "peak_ram_main_lifetime_gb", ".2f"),
    ("GPU utilisation mean (%)", "gpu_util_mean_pct", ".1f"),
    ("GPU utilisation median (%)", "gpu_util_median_pct", ".1f"),
    ("Model time / frame, batched (ms)", "model_time_per_frame_ms", ".2f"),
    ("Model FPS, batched", "model_fps", ".1f"),
    ("Latency / frame, batch 1 mean (ms)", "latency_bs1_mean_ms", ".2f"),
    ("Latency / frame, batch 1 p95 (ms)", "latency_bs1_p95_ms", ".2f"),
    ("FPS, batch 1", "fps_bs1", ".1f"),
    ("End-to-end time / frame (ms)", "end_to_end_time_per_frame_ms", ".2f"),
    ("End-to-end FPS", "end_to_end_fps", ".1f"),
]


def efficiency_table(profiles):
    rows = []
    for label, key, spec in EFFICIENCY_ROWS:
        vals = [p.get(key) if p else None for p in profiles]
        if key == "device":
            vals = [v.replace("NVIDIA ", "") if v else v for v in vals]
        rows.append([label] + [fmt(v, spec) for v in vals])
    return table(["Metric"] + [MODEL_LABEL[m] for m in MODELS], rows, first_w=40)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path("/work/tesi_eprato01/ATLAS_inference"))
    parser.add_argument("--video", default="aries_crop_2025-08-25_073541_VID001")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "results_ex_2.txt")
    args = parser.parse_args()

    vid_info, vid_summary, ev_summary, ev_class = {}, {}, {}, {}
    for m in MODELS:
        pdir = args.root / args.video / f"predictions_{m}"
        edir = args.root / "cholecseg8k" / f"eval_{m}_clip1"
        info = load_json(pdir / "run_info.json")
        # only runs made with the profiling code count (older runs have no "profiling")
        vid_info[m] = info if info and "profiling" in info else None
        vid_summary[m] = load_json(pdir / "summary.json") if vid_info[m] else None
        s = load_json(edir / "summary.json")
        ev_summary[m] = s if s and "profiling" in s else None
        if ev_summary[m] and (edir / "per_class.csv").exists():
            with open(edir / "per_class.csv") as f:
                ev_class[m] = {r["class"]: r for r in csv.DictReader(f)}

    out = []
    w = out.append
    w("ATLAS - EXPERIMENT 2: EFFICIENCY AND ACCURACY OF THE THREE BACKBONES (ViT-S / ViT-B / ViT-L)")
    w("=" * 96)
    w(f"Generated by inference/collect_results.py on {date.today()}  ('pending' = job not finished yet)")
    w("")
    w("Checkpoints (ATLAS finetuned on ATLAS-120k, from the README links):")
    for m in MODELS:
        w(f"  {MODEL_LABEL[m]}: /work/tesi_eprato01/checkpoints/ATLAS/vit-{m[-1]}/atlas_{m}.ckpt")
    w("Common settings: per-frame inference (clip_length 1, as the repo's validation), fp16 autocast,")
    w("same GPU type for every run (SLURM --constraint=gpu_RTX_A5000_24G), 6 DataLoader workers.")
    w("")

    # ---------------------------------------------------------------- experiment A
    w("")
    w("1) VIDEO INFERENCE - aries_crop_2025-08-25_073541_VID001.mp4 (5608 frames, 30 fps, 186.9 s)")
    w("-" * 96)
    w("End-to-end here includes reading the JPGs, writing 5608 PNG masks and encoding the 1920x1080")
    w("overlay video, so it is limited by I/O and CPU, not by the model.")
    w("")
    w(efficiency_table([vid_info[m]["profiling"] | {"device": vid_info[m]["device"]} if vid_info[m] else None
                        for m in MODELS]))
    w("")
    rows = []
    for label, key, spec in [("Mean pixel confidence", "mean_confidence", ".3f"),
                             ("Classes seen (of 29, no background)", "num_classes_seen", "d"),
                             ("Mean classes per frame", "mean_classes_per_frame", ".2f"),
                             ("Procedure top-1", "procedure_top1", ""),
                             ("Procedure top-1 probability", "procedure_top1_prob", ".3f")]:
        rows.append([label] + [fmt(vid_summary[m].get(key) if vid_summary[m] else None, spec) for m in MODELS])
    w("Descriptive output (no ground truth for this video):")
    w(table(["Metric"] + [MODEL_LABEL[m] for m in MODELS], rows, first_w=40))
    w("")

    # ---------------------------------------------------------------- experiment B
    w("")
    w("2) CHOLECSEG8K EVALUATION (17 videos, 8080 frames, 854x480)")
    w("-" * 96)
    w("End-to-end here includes PNG decoding and metric accumulation, no files are written.")
    w("")
    w(efficiency_table([ev_summary[m]["profiling"] if ev_summary[m] else None for m in MODELS]))
    w("")
    rows = []
    for label, key, spec in [("mIoU (10 shared classes)", "miou", ".4f"),
                             ("mIoU without background", "miou_no_bg", ".4f"),
                             ("mDice", "mdice", ".4f"),
                             ("mDice without background", "mdice_no_bg", ".4f"),
                             ("Pixel accuracy", "pixel_acc", ".4f"),
                             ("Pixels predicted as other ATLAS class", "other_atlas_class_rate", ".4f"),
                             ("Procedure accuracy, per frame", "procedure_frame_acc", ".4f"),
                             ("Procedure accuracy, per video", "procedure_video_acc", ".4f")]:
        rows.append([label] + [fmt(ev_summary[m].get(key) if ev_summary[m] else None, spec) for m in MODELS])
    w("Segmentation and procedure recognition:")
    w(table(["Metric"] + [MODEL_LABEL[m] for m in MODELS], rows, first_w=40))
    w("")
    rows = []
    for name, _, _ in EVAL_CLASSES:
        rows.append([name] + [fmt(float(ev_class[m][name]["iou"]) if m in ev_class else None, ".4f")
                              for m in MODELS])
    w("IoU per class:")
    w(table(["Class"] + [MODEL_LABEL[m] for m in MODELS], rows, first_w=40))
    w("")

    # ---------------------------------------------------------------- relabeling
    w("")
    w("3) HOW CHOLECSEG8K AND ATLAS CLASSES WERE MATCHED (shared label space, eval_cholecseg8k.py)")
    w("-" * 96)
    w("CholecSeg8k has 13 classes, ATLAS 30. Neither label set is converted into the other: both the")
    w("ground truth and the prediction are mapped into 10 shared classes, then compared.")
    w("")
    rows = []
    for i, (name, gt_vals, atlas_ids) in enumerate(EVAL_CLASSES):
        gt = " + ".join(f"{CHOLEC_NAMES.get(v, '?')} ({v})" for v in gt_vals)
        at = " + ".join(f"{CLASS_NAMES[a]} ({a})" for a in atlas_ids)
        rows.append([f"{i} {name}", gt, at])
    lines = [f"{'Shared class':<26}{'CholecSeg8k (mask value)':<44}ATLAS class (id)", "-" * 110]
    lines += [f"{a:<26}{b:<44}{c}" for a, b, c in rows]
    w("\n".join(lines))
    w("")
    w("Ignored ground truth (pixels excluded from every metric): "
      + ", ".join(f"{n} ({v})" for v, n in sorted(IGNORED_GT.items())))
    w("Any other ATLAS prediction (Artery, Nerve, Diaphragm, Cystic plate, Spleen, ...) goes to an")
    w("extra column 'Other ATLAS class': it counts as a false negative of the true class and is never")
    w("a true positive. Grasper and L-hook are merged because ATLAS has a single Tools/camera class;")
    w("Small intestine, Colon/rectum and Stomach are merged because CholecSeg8k has a single")
    w("Gastrointestinal tract class.")
    w("")

    # ---------------------------------------------------------------- definitions
    w("")
    w("4) HOW EACH NUMBER IS MEASURED (inference/profiler.py)")
    w("-" * 96)
    w("""Resolution      Frames are resized (PIL bilinear) so that the short side is 256 px: 1920x1080 and
                854x480 both become 455x256. Two overlapping 256x256 windows cover the long side, so
                every frame costs 2 network passes. Scores are averaged and resized back to the
                input resolution, so the output masks have the original resolution.
Peak GPU mem    'PyTorch alloc' = torch.cuda.max_memory_allocated (tensors only); 'reserved' = memory
                held by PyTorch's caching allocator; 'nvidia-smi' = peak device memory seen by NVML,
                which also includes the CUDA context (~0.3-0.5 GB). All three include the model
                weights resident on the GPU (fp32) plus the activations of one batch.
Peak RAM        'main + workers PSS' = peak of the summed PSS of the Python process and its DataLoader
                workers during inference (PSS splits shared pages, so forked workers are not counted
                twice). 'main incl. load' = ru_maxrss of the main process over its whole life, which
                includes reading the .ckpt file (the checkpoint also holds optimizer state, which is why
                ViT-L reaches several GB here).
GPU util        NVML 'utilization.gpu' sampled every 0.2 s during the loop: % of time at least one
                kernel was running. It does not mean that all GPU cores were busy.
Model time      GPU time of predict() (network forward on both windows + mask/class combination + window
                merge), measured with CUDA events and divided by the number of frames. Batched
                (batch 16 frames = 32 windows), after a warm-up.
Batch-1 latency 200 timed calls of predict() on ONE frame already on the GPU (after 20 warm-up calls),
                with a synchronize before and after. This is the real-time / streaming number.
End-to-end      Wall time of the whole loop / frames: decoding, transfer, model, resizing to full
                resolution and everything written to disk. FPS = 1 / time per frame.
                CAUTION: end-to-end speed and GPU utilisation are limited by CPU decoding (6
                workers) and depend on how busy the shared node is. ViT-S on CholecSeg8k: 61 FPS
                end-to-end in October, 21.6 FPS in November on the same GPU type, with the model
                alone at ~4 ms/frame and the GPU idle most of the time. To compare backbones, use
                model time and batch-1 latency, which do not depend on the CPU.""")
    w("")

    # ---------------------------------------------------------------- observations
    w("")
    w("5) OBSERVATIONS ON THE 9-10 NOV 2026 RUNS")
    w("-" * 96)
    w("""SLURM jobs (all on node huber, RTX A5000 24 GB, 8 CPUs, 32 GB RAM, one job at a time):
    195648 eval  ViT-S   9 Nov 14:24   7.5 min      195649 video ViT-S   9 Nov 16:48  24.0 min
    195650 eval  ViT-B   9 Nov 23:20   6.1 min      195651 video ViT-B  10 Nov 01:24  18.1 min
    195652 eval  ViT-L  10 Nov 03:12   6.1 min      195653 video ViT-L  10 Nov 06:12  12.6 min

Accuracy grows with backbone size: CholecSeg8k mIoU 0.528 -> 0.587 -> 0.612. The biggest
gains are on Gastrointestinal tract (0.49 -> 0.78), Gallbladder (0.58 -> 0.79) and Cystic duct
(0.00 -> 0.18). Hepatic vein and Liver ligament stay near 0 for all three, and the ViT-S
accuracy is the same as in October (mIoU 0.5283 both times; differences only from fp16 rounding).

Model cost is what scales with size: GPU time per frame 4 -> 8 -> 15 ms (batched),
peak GPU memory 4.1 -> 5.1 -> 6.5-7.3 GB (nvidia-smi) at batch size 16. All three fit easily
on a 24 GB GPU; on smaller cards the batch size can be lowered.

Batch-1 latency is ~21 ms for BOTH ViT-S and ViT-B: with one frame (2 windows) per call the
small models cannot fill the GPU, and the time is dominated by fixed per-call overhead (kernel
launches, Python, resizing). Only ViT-L is compute-bound (~36-38 ms). Frame by frame, ViT-S and
ViT-B (46 FPS) are faster than a 30 fps video; ViT-L (26-28 FPS) is just below real time.

End-to-end FPS should NOT be used to compare the backbones: it went UP with model size
(video 4.6 -> 6.2 -> 9.5 FPS) only because the jobs ran at different hours on a node shared with
other users' CPU jobs (ViT-S in the afternoon, ViT-L at 6 am). The GPU was idle most of the time
(mean utilisation 3-18 % on the video, 8-44 % on CholecSeg8k): the bottleneck is the CPU
(decoding JPG/PNG, writing 5608 PNG masks, encoding the 1080p overlay). For the same reason the October end-to-end numbers of ViT-S
(12 FPS video, 61 FPS CholecSeg8k) cannot be compared with these.
GPU utilisation is higher for bigger models simply because each batch keeps the GPU busy longer.

RAM: inference itself needs ~1.8 GB (CholecSeg8k) to ~2.9 GB (video, with the frame buffers
for the overlay) for every backbone. Only loading the checkpoint differs: 5.5 GB for ViT-L,
because the .ckpt file (3.8 GB) also contains the optimizer state. SLURM reports MaxRSS ~9.4 GB
for each whole video job: that also counts report.py, the ffmpeg encoder and the DataLoader
workers, summing RSS over processes (shared pages counted several times), so it is an upper bound, not the model's need.

Procedure head on the video: all three say appendectomy, but only ViT-S is confident (0.69);
ViT-B/ViT-L spread the probability (0.28 / 0.22), consistent with the video not being one of
the 14 ATLAS procedures. Segmentation confidence instead rises with size (0.75 -> 0.87 -> 0.91).""")
    w("")

    # ---------------------------------------------------------------- previous run
    old = Path(args.root) / "_backup_vits_2026-10-23"
    old_vid, old_ev = load_json(old / "video/run_info.json"), load_json(old / "cholecseg8k/summary.json")
    if old_vid or old_ev:
        w("")
        w("6) REFERENCE: FIRST ViT-S RUNS (23 Oct 2026, before profiling was added, other GPUs)")
        w("-" * 96)
        if old_vid:
            w(f"Video:       {old_vid['device']}, end-to-end {old_vid['frames_per_s']:.1f} FPS "
              f"({1000 / old_vid['frames_per_s']:.1f} ms/frame)")
        if old_ev:
            w(f"CholecSeg8k: RTX A5000, end-to-end {old_ev['frames_per_s']:.1f} FPS, mIoU {old_ev['miou']:.4f}, "
              f"mIoU no bg {old_ev['miou_no_bg']:.4f}, pixel acc {old_ev['pixel_acc']:.4f}")
        w("Saved in " + str(old))

    args.out.write_text("\n".join(out) + "\n")
    print(f"Written {args.out}")


if __name__ == "__main__":
    main()
